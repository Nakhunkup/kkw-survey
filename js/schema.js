  function riasecScores(arr) {
    if (!Array.isArray(arr) || arr.length < 12) return null;
    return RIASEC.map((t, i) => ({ ...t, score: (Number(arr[i]) || 0) + (Number(arr[i + 6]) || 0) }));
  }
  function riasecCode(scores) {
    if (!scores) return '';
    return [...scores].sort((a, b) => b.score - a.score || 'RIASEC'.indexOf(a.code) - 'RIASEC'.indexOf(b.code)).slice(0, 3).map((s) => s.code).join('');
  }
  function interpret(mean) {
    if (mean == null || isNaN(mean)) return '';
    if (mean >= 4.51) return 'มากที่สุด';
    if (mean >= 3.51) return 'มาก';
    if (mean >= 2.51) return 'ปานกลาง';
    if (mean >= 1.51) return 'น้อย';
    return 'น้อยที่สุด';
  }

  // ตัวช่วย: แปลง options ที่มี group ปนอยู่ ให้เป็นรายการตัวเลือกจริง (เลข 1..n)
  function realOptions(list) {
    const out = [];
    let group = '';
    (list || []).forEach((o) => {
      if (o && o.group) { group = o.group; return; }
      const obj = typeof o === 'string' ? { label: o } : o;
      out.push({ ...obj, group, value: out.length + 1 });
    });
    return out;
  }
  function allQuestions(survey) {
    const qs = [];
    survey.sections.forEach((s, si) => s.questions.forEach((q) => qs.push({ ...q, sectionIndex: si, sectionShowIf: s.showIf })));
    return qs;
  }
  function isVisible(q, answers) {
    if (q.sectionShowIf && !q.sectionShowIf(answers)) return false;
    if (q.showIf && !q.showIf(answers)) return false;
    return true;
  }

